"""
src/main.py
=============

Phase 6 — orchestrates the entire pipeline end to end:

    1. Deterministic match (Phase 3) over the raw datasets.
    2. AI agent investigation (Phase 5) over whatever the deterministic
       layer could not clear, via a real MCP client/server round trip
       (Phase 4).
    3. Write three outputs:
         - data/reconciled_ledger.json   (every resolved record, either
           layer, with its match_type and reasoning)
         - data/audit_trail.md           (regulator-ready paper trail)
         - data/honest_exceptions.json   (records nobody could resolve,
           with the reasoning for why, and a recommended human action)

Run with:
    python -m src.main
"""
import argparse
import asyncio
import time
from pathlib import Path
from typing import List

from src.agent.reconciler import run_agent_reconciliation
from src.deterministic.matcher import run_deterministic_match
from src.models import AgentRunResult, DeterministicMatchResult, MatchedRecord

_REPO_ROOT = Path(__file__).resolve().parents[1]
_DATA_DIR = _REPO_ROOT / "data"
_MERCHANT_SALES = _DATA_DIR / "merchant_sales.json"
_RAZORPAY_PAYOUTS = _DATA_DIR / "razorpay_payouts.json"
_SERVER_SCRIPT = _REPO_ROOT / "src" / "mcp_server" / "server.py"


def _is_missing_payout(record_payout_id: str) -> bool:
    """Return whether this is a synthetic record for an absent payout."""
    return record_payout_id.startswith("NO_PAYOUT_FOUND:")


def _percentage(numerator: int, denominator: int) -> str:
    """Format a safe percentage for empty input batches too."""
    return f"{(numerator / denominator if denominator else 0):.1%}"


def _write_deterministic_handoff(result: DeterministicMatchResult) -> None:
    """The MCP server reads this file to know what it's allowed to expose.
    This IS the security boundary described in Phase 4: the agent only ever
    sees what gets written here, never the raw source files."""
    (_DATA_DIR / "deterministic_result.json").write_text(result.model_dump_json(indent=2), encoding="utf-8")


def _build_audit_trail_markdown(
    det: DeterministicMatchResult,
    agent: AgentRunResult,
    elapsed_seconds: float,
    engine: str = "rules",
) -> str:
    missing_payout_orders = sum(1 for u in det.unresolved if _is_missing_payout(u.payout_id))
    total_cases = det.total_payouts + missing_payout_orders
    total_resolved = len(det.matched) + len(agent.resolved)
    lines: List[str] = []
    lines.append("# Settlement Reconciliation — Audit Trail")
    lines.append("")
    lines.append(f"_Generated by the Automated Settlement Reconciliation Engine in {elapsed_seconds:.3f}s "
                 f"using the **{engine}** reasoning engine._")
    lines.append("")
    lines.append("## 1. Throughput & Accuracy")
    lines.append("")
    lines.append(f"- **Merchant orders processed:** {det.total_merchant_orders}")
    lines.append(f"- **Payout records processed:** {det.total_payouts}")
    lines.append(f"- **Deterministic matches (Phase 3, zero AI):** {len(det.matched)} "
                 f"({_percentage(len(det.matched), det.total_payouts)} of payouts)")
    lines.append(f"- **AI-resolved matches (Phase 5, confidence ≥ {agent.confidence_threshold:.0%}):** "
                 f"{len(agent.resolved)}")
    lines.append(f"- **Honest exceptions (confidence below threshold):** {len(agent.exceptions)}")
    lines.append(f"- **Orders with no payout record:** {missing_payout_orders}")
    lines.append(f"- **Overall resolution rate:** {total_resolved}/{total_cases} reconciliation cases "
                 f"({_percentage(total_resolved, total_cases)})")
    lines.append(f"- **Total processing time:** {elapsed_seconds:.3f} seconds")
    lines.append("")

    lines.append("## 2. Deterministic Matches (Phase 3)")
    lines.append("")
    lines.append("Exact 1:1 amount matches. No AI reasoning involved — these are matched "
                 "because the settled amount equals the merchant-expected amount to the cent.")
    lines.append("")
    lines.append("| Payout ID | Order(s) | Merchant Total (₹) | Settled (₹) |")
    lines.append("|---|---|---|---|")
    for m in det.matched[:15]:
        lines.append(f"| {m.payout_id} | {', '.join(m.order_ids)} | {m.merchant_total:.2f} | {m.settled_amount:.2f} |")
    if len(det.matched) > 15:
        lines.append(f"| ... | *{len(det.matched) - 15} more clean matches omitted for brevity* | | |")
    lines.append("")

    lines.append("## 3. AI-Driven Matches — Full Reasoning (Phase 5)")
    lines.append("")
    lines.append("Every record below was routed to the AI agent because the deterministic "
                 "layer could not clear it with zero-tolerance exact matching. The agent "
                 "investigated each one through the MCP server's read-only tools "
                 "(`calculate_variance`, `fetch_historical_fees`, `simulate_tax_deduction`) "
                 "and only auto-matched records where its confidence met or exceeded "
                 f"**{agent.confidence_threshold:.0%}**.")
    lines.append("")
    if not agent.resolved:
        lines.append("_No records met the AI confidence threshold in this run._")
    for r in agent.resolved:
        lines.append(f"### {r.payout_id} — orders {', '.join(r.order_ids)}")
        lines.append(f"- **Confidence:** {r.confidence:.0%}")
        lines.append(f"- **Merchant total:** ₹{r.merchant_total:.2f}  |  **Settled:** ₹{r.settled_amount:.2f}")
        lines.append(f"- **MCP tools invoked:** {', '.join(r.tools_invoked)}")
        lines.append(f"- **Reasoning:** {r.explanation}")
        lines.append("")

    lines.append("## 4. Honest Exception List — Graceful Failure Recovery")
    lines.append("")
    lines.append("These records could NOT be confidently resolved. Per the system's "
                 "guardrails, low-confidence guesses are never silently written to the "
                 "ledger — they are surfaced here for human review instead.")
    lines.append("")
    if not agent.exceptions:
        lines.append("_No exceptions in this run — every unresolved record met the confidence threshold._")
    for e in agent.exceptions:
        lines.append(f"### {e.payout_id} — orders {', '.join(e.order_ids)}")
        lines.append(f"- **Confidence:** {e.confidence:.0%} (below {agent.confidence_threshold:.0%} threshold)")
        lines.append(f"- **Merchant total:** ₹{e.merchant_total:.2f}  |  **Settled:** ₹{e.settled_amount:.2f}")
        lines.append(f"- **MCP tools invoked:** {', '.join(e.tools_invoked)}")
        lines.append(f"- **Reasoning:** {e.explanation}")
        lines.append(f"- **Recommended human action:** {e.recommended_human_action}")
        lines.append("")

    no_payout = [u for u in det.unresolved if _is_missing_payout(u.payout_id)]
    if no_payout:
        lines.append("## 5. Orders With No Corresponding Payout At All")
        lines.append("")
        lines.append("These merchant orders never appear in the Razorpay settlement file. "
                     "This is not a matching-confidence issue — it is a missing-data issue "
                     "that needs escalation to the payments team directly.")
        lines.append("")
        for u in no_payout:
            lines.append(f"- Order `{u.linked_orders[0]}` — expected ₹{u.merchant_total:.2f}, no payout found.")
        lines.append("")

    return "\n".join(lines)


def run_pipeline(engine: str = "rules") -> None:
    start = time.perf_counter()

    print("=" * 72)
    print("AUTOMATED SETTLEMENT RECONCILIATION ENGINE — Razorpay AI Buildathon")
    print("Track 04 — AI Finance Controller")
    print(f"Reasoning engine: {engine.upper()}"
          + ("  (hand-coded decision table)" if engine == "rules" else "  (trained classifier)"))
    print("=" * 72)

    print("\n[Phase 3] Running deterministic matcher...")
    det_result = run_deterministic_match(_MERCHANT_SALES, _RAZORPAY_PAYOUTS)
    _write_deterministic_handoff(det_result)
    print(f"  -> {len(det_result.matched)} matched deterministically, "
          f"{len(det_result.unresolved)} routed to the AI agent.")

    print("\n[Phase 4/5] Starting MCP server + AI agent investigation...")
    agent_result: AgentRunResult = asyncio.run(
        run_agent_reconciliation(det_result.unresolved, _SERVER_SCRIPT, engine=engine)
    )
    print(f"  -> AI resolved {len(agent_result.resolved)} records "
          f"(confidence >= {agent_result.confidence_threshold:.0%}).")
    print(f"  -> {len(agent_result.exceptions)} records pushed to the Honest Exception List.")

    elapsed = time.perf_counter() - start

    print("\n[Phase 6] Writing reconciled ledger, audit trail, and exception list...")

    reconciled_ledger = {
        "deterministic_matches": [m.model_dump() for m in det_result.matched],
        "ai_resolved_matches": [r.model_dump() for r in agent_result.resolved],
        "summary": {
            "total_payouts": det_result.total_payouts,
            "missing_payout_order_count": sum(
                1 for record in det_result.unresolved if _is_missing_payout(record.payout_id)
            ),
            "total_reconciliation_cases": det_result.total_payouts + sum(
                1 for record in det_result.unresolved if _is_missing_payout(record.payout_id)
            ),
            "deterministic_match_count": len(det_result.matched),
            "ai_resolved_count": len(agent_result.resolved),
            "exception_count": len(agent_result.exceptions),
            "processing_time_seconds": round(elapsed, 3),
        },
    }
    (_DATA_DIR / "reconciled_ledger.json").write_text(
        __import__("json").dumps(reconciled_ledger, indent=2), encoding="utf-8"
    )

    (_DATA_DIR / "honest_exceptions.json").write_text(
        __import__("json").dumps([e.model_dump() for e in agent_result.exceptions], indent=2),
        encoding="utf-8",
    )

    audit_md = _build_audit_trail_markdown(det_result, agent_result, elapsed, engine=engine)
    (_DATA_DIR / "audit_trail.md").write_text(audit_md, encoding="utf-8")

    print(f"  -> data/reconciled_ledger.json")
    print(f"  -> data/honest_exceptions.json")
    print(f"  -> data/audit_trail.md")

    print("\n" + "=" * 72)
    print("SUMMARY")
    print("=" * 72)
    total_resolved = len(det_result.matched) + len(agent_result.resolved)
    print(f"Total payouts processed:      {det_result.total_payouts}")
    print(f"Deterministic match rate:     {_percentage(len(det_result.matched), det_result.total_payouts)}")
    print(f"AI-assisted match rate:       {len(agent_result.resolved) / det_result.total_payouts:.1%}")
    total_cases = det_result.total_payouts + sum(
        1 for record in det_result.unresolved if _is_missing_payout(record.payout_id)
    )
    print(f"Combined resolution rate:     {_percentage(total_resolved, total_cases)}")
    print(f"Honest exceptions:            {len(agent_result.exceptions)}")
    print(f"Total processing time:        {elapsed:.3f}s")
    print("=" * 72)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Automated Settlement Reconciliation Engine")
    parser.add_argument(
        "--engine",
        choices=["rules", "ml"],
        default="rules",
        help="Reasoning engine for the AI agent's investigation step. 'rules' (default) is the "
        "hand-coded, always-available decision table. 'ml' uses the classifier trained by "
        "`python -m data.training.train_model` on the 10 dummy edge-case batches — run that "
        "first or this will raise FileNotFoundError.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    args = _parse_args()
    run_pipeline(engine=args.engine)
